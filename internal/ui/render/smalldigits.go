package render

import "github.com/wicanr2/great-era-remake/internal/assets"

// 戰鬥畫面用的小數字。
//
// # 為什麼要第二套
//
// 原版**政略畫面與戰鬥畫面用不同大小的數字**（`docs/playtest/14` 量到）：
//
//	政略面板   字寬 11、字距 16   （digits.go）
//	戰鬥面板   字寬  6、字距  8   （這裡）
//
// 戰鬥面板要在 188 px 寬的欄位裡塞下兩組五位數 + 三字標籤，
// 用政略那套 16 px 字距會直接溢出（5 × 16 = 80 px，兩組就吃掉整個面板）。
//
// # [remake 差異] 字形是自己畫的
//
// 與 `digits.go` 同一個處境：**原版的數字字模在檔案裡找不到**
// （搜過 IBM ROM 字型、BGI `.CHR` 簽名、`.GLB` 解壓內容，全部落空）。
// 這裡照量到的尺寸（6 × 14、筆劃 1 px）自己畫一套。
//
// 解出原版字型之後要換掉。**這一項已標記為 remake 差異**（`CLAUDE.md` §1）。

// SmallDigitW / SmallDigitH 是戰鬥面板數字的尺寸，從實機截圖量到。
const (
	SmallDigitW, SmallDigitH = 6, 14
	// SmallDigitAdvance 是字距。實機「33472」五個數字的左邊界是
	// 470／478／486／494／502，間隔一律 8。
	SmallDigitAdvance = 8
)

// smallDigitArt 是 0-9 的點陣，`#` 是前景。筆劃 1 px，不加粗。
var smallDigitArt = [10][SmallDigitH]string{
	{".####.", "#....#", "#....#", "#....#", "#....#", "#....#", "#....#",
		"#....#", "#....#", "#....#", "#....#", "#....#", "#....#", ".####."},
	{"..##..", ".###..", "####..", "..##..", "..##..", "..##..", "..##..",
		"..##..", "..##..", "..##..", "..##..", "..##..", "######", "######"},
	{".####.", "#....#", "#....#", ".....#", ".....#", ".....#", "....#.",
		"...#..", "..#...", ".#....", "#.....", "#.....", "######", "######"},
	{".####.", "#....#", ".....#", ".....#", ".....#", "..###.", "..###.",
		".....#", ".....#", ".....#", ".....#", "#....#", "#....#", ".####."},
	{"....#.", "...##.", "..#.#.", ".#..#.", "#...#.", "#...#.", "######",
		"######", "....#.", "....#.", "....#.", "....#.", "....#.", "....#."},
	{"######", "######", "#.....", "#.....", "#.....", "#####.", "#....#",
		".....#", ".....#", ".....#", ".....#", "#....#", "#....#", ".####."},
	{".####.", "#....#", "#.....", "#.....", "#.....", "#####.", "#....#",
		"#....#", "#....#", "#....#", "#....#", "#....#", "#....#", ".####."},
	{"######", "######", ".....#", ".....#", "....#.", "....#.", "...#..",
		"...#..", "..#...", "..#...", ".#....", ".#....", "#.....", "#....."},
	{".####.", "#....#", "#....#", "#....#", "#....#", ".####.", ".####.",
		"#....#", "#....#", "#....#", "#....#", "#....#", "#....#", ".####."},
	{".####.", "#....#", "#....#", "#....#", "#....#", "#....#", ".#####",
		".....#", ".....#", ".....#", ".....#", "#....#", "#....#", ".####."},
}

// smallDigitBits 是把 art 編成位元遮罩，畫的時候不必再比字元。
var smallDigitBits = func() [10][SmallDigitH]uint8 {
	var out [10][SmallDigitH]uint8
	for d := range smallDigitArt {
		for y, row := range smallDigitArt[d] {
			var bits uint8
			for x := 0; x < SmallDigitW && x < len(row); x++ {
				if row[x] == '#' {
					bits |= 1 << (7 - x)
				}
			}
			out[d][y] = bits
		}
	}
	return out
}()

// DrawSmallDigit 把一個數字（0-9）畫到 (x, y)。超出範圍的值不畫。
func (c *Canvas) DrawSmallDigit(d int, fg assets.RGB, x, y int) {
	if d < 0 || d > 9 {
		return
	}
	for gy := 0; gy < SmallDigitH; gy++ {
		row := smallDigitBits[d][gy]
		for gx := 0; gx < SmallDigitW; gx++ {
			if row&(1<<(7-gx)) != 0 {
				c.setPixel(x+gx, y+gy, fg)
			}
		}
	}
}

// DrawSmallNumber 把一個非負整數靠右對齊畫到 (right, y)。
//
// 戰鬥面板的兩欄數值都靠右對齊（`docs/playtest/14`：攻方右邊界 508、
// 守方 627），與政略面板同一個習慣。
func (c *Canvas) DrawSmallNumber(v uint32, fg assets.RGB, right, y int) {
	digits := []int{int(v % 10)}
	for v /= 10; v > 0; v /= 10 {
		digits = append(digits, int(v%10))
	}
	for i, d := range digits {
		x := right - (i+1)*SmallDigitAdvance + (SmallDigitAdvance - SmallDigitW)
		c.DrawSmallDigit(d, fg, x, y)
	}
}

// SmallNumberWidth 回傳一個數字用小字畫出來要多寬。
func SmallNumberWidth(v uint32) int {
	n := 1
	for v >= 10 {
		v /= 10
		n++
	}
	return n * SmallDigitAdvance
}
