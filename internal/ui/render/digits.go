// digitBits 是預先轉好的點陣，每個數字 DigitH 列、每列一個 uint16（bit 15 在左）。
var digitBits = func() [10][DigitH]uint16 {
	var out [10][DigitH]uint16
	for d := range digitArt {
		for y, row := range digitArt[d] {
			var bits uint16
			for x := 0; x < DigitW && x < len(row); x++ {
				if row[x] == '#' {
					bits |= 1 << (15 - x)
				}
			}
			// 與中文字模一樣的加粗：與自己右移一位 OR，筆劃變 3 px。
			out[d][y] = bits | bits>>1
		}
	}
	return out
}()

// DrawDigit 把一個數字（0-9）畫到 (x, y)。超出範圍的值不畫。
func (c *Canvas) DrawDigit(d int, fg assets.RGB, x, y int) {
	if d < 0 || d > 9 {
		return
	}
	for gy := 0; gy < DigitH; gy++ {
		row := digitBits[d][gy]
		for gx := 0; gx < DigitW+1; gx++ {
			if row&(1<<(15-gx)) != 0 {
				c.setPixel(x+gx, y+gy, fg)
			}
		}
	}
}

// DrawNumber 把一個非負整數靠右對齊畫到 (right, y)，右邊界是 right。
//
// 原版政略畫面的數值全部靠右對齊（截圖量到「4150」與「97500」的右邊界一致），
// 所以這裡也靠右。
func (c *Canvas) DrawNumber(v uint32, fg assets.RGB, right, y int) {
	digits := []int{int(v % 10)}
	for v /= 10; v > 0; v /= 10 {
		digits = append(digits, int(v%10))
	}
	for i, d := range digits {
		c.DrawDigit(d, fg, right-(i+1)*DigitAdvance+(DigitAdvance-DigitW), y)
	}
}

// NumberWidth 回傳一個數字畫出來要多寬。
func NumberWidth(v uint32) int {
	n := 1
	for v >= 10 {
		v /= 10
		n++
	}
	return n * DigitAdvance
}
