// 但**那些字模在原版檔案裡找不到**：搜過 IBM 8×8 與 8×14 ROM 字型的圖樣、
// BGI stroked font 的 `.CHR` 簽名、DCL 解壓後的 `.GLB` 內容，全部落空
// （`CONTEXT.md` worklist）。副檔名 `.CHR` 的字串只是 Turbo Pascal Graph unit
